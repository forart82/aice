import type {
  Block,
  CallExpr,
  ClassDecl,
  ConstDecl,
  Expr,
  FunctionDecl,
  ImportDecl,
  MatchStmt,
  MethodDecl,
  Module,
  ModuleItem,
  Pattern,
  Statement,
  TypeDecl,
  TypeExpr,
  VarDecl,
} from "../core/ast.js";
import { EmitterContext, type EmitterOptions } from "./context.js";
import { lowerConstructor, lowerMethodCall, lowerPropertyAccess } from "./rewriter.js";

export class RustEmitter {
  private ctx: EmitterContext;
  private structTypes: Map<string, string[]> = new Map();
  private enumVariants: Map<string, { parentEnum: string; payloadTypes?: TypeExpr[] }> = new Map();

  constructor(options: EmitterOptions = {}) {
    this.ctx = new EmitterContext("rust", {
      ...options,
      indent: options.indent ?? "    ",
    });
  }

  emit(mod: Module): string {
    return this.emitModule(mod);
  }

  emitModule(mod: Module): string {
    this.structTypes.clear();
    this.enumVariants.clear();

    let hasHashMap = false;
    let hasStructs = false;

    for (const item of mod.items) {
      if (item.kind === "TypeDecl") {
        if (item.fields) {
          hasStructs = true;
          this.structTypes.set(
            item.name,
            item.fields.map((f) => f.name),
          );
        } else if (item.isEnum && item.variants) {
          for (const v of item.variants) {
            this.enumVariants.set(v.name, {
              parentEnum: item.name,
              payloadTypes: v.payloadTypes,
            });
          }
        }
      } else if (item.kind === "ClassDecl") {
        hasStructs = true;
        const fieldNames: string[] = [];
        if (item.primaryConstructor) {
          for (const p of item.primaryConstructor) fieldNames.push(p.name);
        }
        if (item.properties) {
          for (const p of item.properties) fieldNames.push(p.name);
        }
        this.structTypes.set(item.name, fieldNames);
      }
    }

    const checkType = (t?: TypeExpr | null) => {
      if (!t) return;
      if (t.kind === "NamedType") {
        if (t.name === "Map" || t.name === "HashMap") hasHashMap = true;
        if (t.typeArgs) t.typeArgs.forEach(checkType);
      }
      if (t.kind === "ArrayType") checkType(t.elementType);
      if (t.kind === "TupleType") t.elementTypes.forEach(checkType);
      if (t.kind === "OptionType") checkType(t.innerType);
      if (t.kind === "ResultType") {
        checkType(t.okType);
        checkType(t.errType);
      }
    };

    for (const item of mod.items) {
      if (item.kind === "TypeDecl") {
        if (item.fields) {
          for (const f of item.fields) checkType(f.typeAnnotation);
        }
      } else if (item.kind === "ClassDecl") {
        if (item.primaryConstructor) {
          for (const p of item.primaryConstructor) checkType(p.typeAnnotation);
        }
        if (item.properties) {
          for (const p of item.properties) checkType(p.typeAnnotation);
        }
        for (const m of item.methods) {
          for (const p of m.params) checkType(p.typeAnnotation);
          checkType(m.returnType);
        }
      } else if (item.kind === "ConstDecl" || item.kind === "VarDecl") {
        checkType(item.typeAnnotation);
      } else if (item.kind === "FunctionDecl") {
        for (const p of item.params) if (p.typeAnnotation) checkType(p.typeAnnotation);
        checkType(item.returnType);
      }
    }

    this.ctx.writeLine("// Auto-generated by AICE 2.0 Rust Emitter (Rust 2021 Edition)");
    this.ctx.writeLine("#![allow(unused_imports, dead_code, unused_variables)]");
    this.ctx.writeLine();

    if (hasHashMap) {
      this.ctx.writeLine("use std::collections::HashMap;");
    }
    if (hasStructs || this.enumVariants.size > 0) {
      this.ctx.writeLine("use serde::{Serialize, Deserialize};");
    }

    const imports = mod.items.filter((i) => i.kind === "ImportDecl") as ImportDecl[];
    const nonImports = mod.items.filter((i) => i.kind !== "ImportDecl");

    for (const imp of imports) {
      this.emitImport(imp);
    }

    if (imports.length > 0 || hasHashMap || hasStructs) {
      this.ctx.writeLine();
    }

    for (let i = 0; i < nonImports.length; i++) {
      this.emitModuleItem(nonImports[i]);
      if (i < nonImports.length - 1) {
        this.ctx.writeLine();
      }
    }

    return this.ctx.getOutput();
  }

  private emitImport(imp: ImportDecl): void {
    const rustPath = imp.source.replace(/\//g, "::").replace(/\.[a-zA-Z]+$/, "");
    if (imp.specifiers.length === 1 && imp.specifiers[0].isWildcard) {
      this.ctx.writeLine(`use ${rustPath}::*;`);
      return;
    }
    const specs = imp.specifiers.map((s) => (s.alias ? `${s.name} as ${s.alias}` : s.name));
    this.ctx.writeLine(`use ${rustPath}::{${specs.join(", ")}};`);
  }

  private emitModuleItem(item: ModuleItem): void {
    switch (item.kind) {
      case "TypeDecl":
        this.emitTypeDecl(item);
        break;
      case "ClassDecl":
        this.emitClassDecl(item);
        break;
      case "ConstDecl":
        this.emitConstDecl(item);
        break;
      case "VarDecl":
        this.emitVarDecl(item);
        break;
      case "FunctionDecl":
        this.emitFunctionDecl(item);
        break;
      default:
        break;
    }
  }

  private emitTypeDecl(t: TypeDecl): void {
    const nodeId = `type:${t.name}`;
    this.ctx.emitLeadingTrivia(nodeId);

    if (t.aliasType) {
      if (t.aliasType.kind === "RecordType") {
        this.ctx.writeLine("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]");
        this.ctx.writeLine(`pub struct ${t.name} {`);
        this.ctx.indent();
        for (const f of t.aliasType.fields) {
          this.ctx.writeLine(`pub ${this.toSnakeCase(f.name)}: ${this.emitTypeExpr(f.type)},`);
        }
        this.ctx.dedent();
        this.ctx.writeLine("}");
        this.ctx.emitTrailingTrivia(nodeId);
        return;
      }
      const typeStr = this.emitTypeExpr(t.aliasType);
      this.ctx.writeLine(`pub type ${t.name} = ${typeStr};`);
      this.ctx.emitTrailingTrivia(nodeId);
      return;
    }

    if (t.isEnum && t.variants) {
      this.ctx.writeLine("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]");
      this.ctx.writeLine(`pub enum ${t.name} {`);
      this.ctx.indent();
      for (const v of t.variants) {
        if (!v.payloadTypes || v.payloadTypes.length === 0) {
          this.ctx.writeLine(`${v.name},`);
        } else {
          const payloads = v.payloadTypes.map((pt) => this.emitTypeExpr(pt)).join(", ");
          this.ctx.writeLine(`${v.name}(${payloads}),`);
        }
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.emitTrailingTrivia(nodeId);
      return;
    }

    if (t.fields) {
      this.ctx.writeLine("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]");
      this.ctx.writeLine(`pub struct ${t.name} {`);
      this.ctx.indent();
      for (const f of t.fields) {
        const fieldNodeId = `field:${t.name}.${f.name}`;
        this.ctx.emitLeadingTrivia(fieldNodeId);
        this.ctx.writeLine(
          `pub ${this.toSnakeCase(f.name)}: ${this.emitTypeExpr(f.typeAnnotation)},`,
        );
        this.ctx.emitTrailingTrivia(fieldNodeId);
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");

      this.ctx.writeLine();
      const params = t.fields
        .map((f) => `${this.toSnakeCase(f.name)}: ${this.emitTypeExpr(f.typeAnnotation)}`)
        .join(", ");
      const fieldAssigns = t.fields.map((f) => this.toSnakeCase(f.name)).join(", ");
      this.ctx.writeLine(`impl ${t.name} {`);
      this.ctx.indent();
      this.ctx.writeLine(`pub fn new(${params}) -> Self {`);
      this.ctx.indent();
      this.ctx.writeLine(`Self { ${fieldAssigns} }`);
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.emitTrailingTrivia(nodeId);
    }
  }

  private inferRustType(val: Expr): string {
    if (val.kind === "LiteralExpr") {
      if (val.literalKind === "string") return "&str";
      if (val.literalKind === "boolean") return "bool";
      if (val.literalKind === "number") {
        return Number.isInteger(val.value) ? "i64" : "f64";
      }
    }
    return "i64";
  }

  private emitConstDecl(c: ConstDecl): void {
    const nodeId = `const:${c.name}`;
    this.ctx.emitLeadingTrivia(nodeId);
    const name = c.name.toUpperCase() === c.name ? c.name : this.toSnakeCase(c.name).toUpperCase();
    const typeStr = c.typeAnnotation
      ? this.emitTypeExpr(c.typeAnnotation)
      : this.inferRustType(c.value);
    const valStr =
      typeStr === "&str" && c.value.kind === "LiteralExpr" && c.value.literalKind === "string"
        ? JSON.stringify(c.value.value)
        : this.emitExpr(c.value);
    this.ctx.writeLine(`pub const ${name}: ${typeStr} = ${valStr};`);
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitVarDecl(v: VarDecl): void {
    const nodeId = `var:${v.name}`;
    this.ctx.emitLeadingTrivia(nodeId);
    const name = v.name.toUpperCase() === v.name ? v.name : this.toSnakeCase(v.name).toUpperCase();
    const typeStr = v.typeAnnotation
      ? this.emitTypeExpr(v.typeAnnotation)
      : this.inferRustType(v.value);
    const valStr =
      typeStr === "&str" && v.value.kind === "LiteralExpr" && v.value.literalKind === "string"
        ? JSON.stringify(v.value.value)
        : this.emitExpr(v.value);
    if (v.isMut) {
      this.ctx.writeLine(`pub static mut ${name}: ${typeStr} = ${valStr};`);
    } else {
      this.ctx.writeLine(`pub const ${name}: ${typeStr} = ${valStr};`);
    }
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitClassDecl(cls: ClassDecl): void {
    const nodeId = `class:${cls.name}`;
    this.ctx.emitLeadingTrivia(nodeId);

    const fields: { name: string; typeAnnotation?: TypeExpr }[] = [];
    const seen = new Set<string>();
    if (cls.primaryConstructor) {
      for (const p of cls.primaryConstructor) {
        if (!seen.has(p.name)) {
          seen.add(p.name);
          fields.push({ name: p.name, typeAnnotation: p.typeAnnotation ?? undefined });
        }
      }
    }
    if (cls.properties) {
      for (const p of cls.properties) {
        if (!seen.has(p.name)) {
          seen.add(p.name);
          fields.push({ name: p.name, typeAnnotation: p.typeAnnotation ?? undefined });
        }
      }
    }

    this.ctx.writeLine("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]");
    this.ctx.writeLine(`pub struct ${cls.name} {`);
    this.ctx.indent();
    for (const f of fields) {
      const fieldNodeId = `field:${cls.name}.${f.name}`;
      this.ctx.emitLeadingTrivia(fieldNodeId);
      const fieldName = this.toSnakeCase(f.name);
      const typeStr = f.typeAnnotation ? this.emitTypeExpr(f.typeAnnotation) : "()";
      this.ctx.writeLine(`pub ${fieldName}: ${typeStr},`);
      this.ctx.emitTrailingTrivia(fieldNodeId);
    }
    this.ctx.dedent();
    this.ctx.writeLine("}");

    this.ctx.writeLine();
    this.ctx.writeLine(`impl ${cls.name} {`);
    this.ctx.indent();

    const ctorMethod = cls.methods.find(
      (m) =>
        m.name === "constructor" ||
        m.name === "new" ||
        m.name === `New${cls.name}` ||
        m.name === cls.name,
    );

    if (cls.primaryConstructor || ctorMethod || fields.length > 0) {
      const ctorParams = (ctorMethod ? ctorMethod.params : (cls.primaryConstructor ?? fields))
        .map(
          (f) =>
            `${this.toSnakeCase(f.name)}: ${f.typeAnnotation ? this.emitTypeExpr(f.typeAnnotation) : "_"}`,
        )
        .join(", ");
      this.ctx.writeLine(`pub fn new(${ctorParams}) -> Self {`);
      this.ctx.indent();
      const fieldAssigns = fields.map((f) => this.toSnakeCase(f.name)).join(", ");
      this.ctx.writeLine(`Self { ${fieldAssigns} }`);
      this.ctx.dedent();
      this.ctx.writeLine("}");
    }

    const nonCtorMethods = cls.methods.filter((m) => m !== ctorMethod);
    for (let i = 0; i < nonCtorMethods.length; i++) {
      const m = nonCtorMethods[i];
      if (cls.primaryConstructor || ctorMethod || fields.length > 0 || i > 0) {
        this.ctx.writeLine();
      }
      const methodNodeId = `method:${cls.name}.${m.name}`;
      this.ctx.emitLeadingTrivia(methodNodeId);
      const mName = this.toSnakeCase(m.name);
      const paramsList: string[] = [];
      if (!m.isStatic) {
        const isMutating = this.isMethodMutating(m);
        paramsList.push(isMutating ? "&mut self" : "&self");
      }
      for (const p of m.params) {
        if (p.name === "self" || p.name === "this") continue;
        const pType = p.typeAnnotation ? this.emitTypeExpr(p.typeAnnotation) : "_";
        paramsList.push(`${this.toSnakeCase(p.name)}: ${pType}`);
      }
      const paramsStr = paramsList.join(", ");
      const retType = m.returnType ? this.emitTypeExpr(m.returnType) : null;
      const retStr = retType && retType !== "()" && retType !== "void" ? ` -> ${retType}` : "";

      this.ctx.writeLine(`pub fn ${mName}(${paramsStr})${retStr} {`);
      this.ctx.indent();
      if (m.isExpressionBodied) {
        const exprCode = this.emitExpr(m.body as Expr);
        this.ctx.writeLine(exprCode);
      } else if (m.body.kind === "Block") {
        this.emitBlock(m.body, !!retStr);
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.emitTrailingTrivia(methodNodeId);
    }

    this.ctx.dedent();
    this.ctx.writeLine("}");
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private isMethodMutating(m: MethodDecl): boolean {
    const check = (node: any): boolean => {
      if (!node) return false;
      if (node.kind === "AssignStmt" || node.kind === "AssignExpr") {
        const target = node.target;
        if (
          target &&
          target.kind === "MemberAccessExpr" &&
          target.object &&
          target.object.kind === "IdentifierExpr" &&
          (target.object.name === "this" || target.object.name === "self")
        ) {
          return true;
        }
      }
      for (const key of Object.keys(node)) {
        const val = node[key];
        if (val && typeof val === "object") {
          if (Array.isArray(val)) {
            for (const item of val) {
              if (check(item)) return true;
            }
          } else {
            if (check(val)) return true;
          }
        }
      }
      return false;
    };
    return check(m.body);
  }

  private emitFunctionDecl(fn: FunctionDecl): void {
    const nodeId = `fn:${fn.name}`;
    this.ctx.emitLeadingTrivia(nodeId);

    if (fn.name === "__top_level__") {
      this.ctx.writeLine("pub fn main() {");
      this.ctx.indent();
      this.emitBlock(fn.body as Block, false);
      this.ctx.dedent();
      this.ctx.writeLine("}");
      return;
    }

    const fnName = this.toSnakeCase(fn.name);
    const paramsStr = fn.params
      .map(
        (p) =>
          `${this.toSnakeCase(p.name)}: ${p.typeAnnotation ? this.emitTypeExpr(p.typeAnnotation) : "_"}`,
      )
      .join(", ");

    const retType = fn.returnType ? this.emitTypeExpr(fn.returnType) : null;
    const retStr = retType && retType !== "()" ? ` -> ${retType}` : "";

    this.ctx.writeLine(`pub fn ${fnName}(${paramsStr})${retStr} {`);
    this.ctx.indent();

    if (fn.isExpressionBodied) {
      const exprCode = this.emitExpr(fn.body as Expr);
      this.ctx.writeLine(exprCode);
    } else {
      this.emitBlock(fn.body as Block, Boolean(retType && retType !== "()"));
    }

    this.ctx.dedent();
    this.ctx.writeLine("}");
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitBlock(block: Block, isReturning: boolean): void {
    const stmts = block.statements;
    for (let i = 0; i < stmts.length; i++) {
      const stmt = stmts[i];
      const isLast = i === stmts.length - 1;
      this.emitStatement(stmt, isLast && isReturning);
    }
  }

  private emitStatement(stmt: Statement, isImplicitReturn = false): void {
    switch (stmt.kind) {
      case "LetBinding": {
        const varName = this.toSnakeCase(stmt.name);
        const typeStr = stmt.typeAnnotation ? `: ${this.emitTypeExpr(stmt.typeAnnotation)}` : "";
        const initStr = ` = ${this.emitExpr(stmt.init)}`;
        const mutStr = stmt.isMut ? "mut " : "";
        this.ctx.writeLine(`let ${mutStr}${varName}${typeStr}${initStr};`);
        break;
      }
      case "DestructureBinding": {
        const mutStr = stmt.isMut ? "mut " : "";
        const names = stmt.names.map((n) => this.toSnakeCase(n)).join(", ");
        this.ctx.writeLine(`let ${mutStr}(${names}) = ${this.emitExpr(stmt.init)};`);
        break;
      }
      case "AssignStmt": {
        if (
          stmt.target.kind === "ArrayLiteralExpr" &&
          stmt.value.kind === "ArrayLiteralExpr" &&
          stmt.value.elements.length === stmt.target.elements.length
        ) {
          for (let i = 0; i < stmt.target.elements.length; i++) {
            const target = this.emitExpr(stmt.target.elements[i]);
            const value = this.emitExpr(stmt.value.elements[i]);
            if (stmt.op === "**=") {
              this.ctx.writeLine(`${target} = ${target}.pow(${value});`);
            } else if (stmt.op === ">>>=") {
              this.ctx.writeLine(`${target} = ((${target} as u64) >> ${value}) as _;`);
            } else {
              this.ctx.writeLine(`${target} ${stmt.op ?? "="} ${value};`);
            }
          }
        } else {
          const target = this.emitExpr(stmt.target);
          const value = this.emitExpr(stmt.value);
          if (stmt.op === "**=") {
            this.ctx.writeLine(`${target} = ${target}.pow(${value});`);
          } else if (stmt.op === ">>>=") {
            this.ctx.writeLine(`${target} = ((${target} as u64) >> ${value}) as _;`);
          } else {
            this.ctx.writeLine(`${target} ${stmt.op ?? "="} ${value};`);
          }
        }
        break;
      }
      case "ReturnStmt": {
        if (!stmt.value) {
          this.ctx.writeLine("return;");
        } else {
          this.ctx.writeLine(`return ${this.emitExpr(stmt.value)};`);
        }
        break;
      }
      case "IfStmt": {
        const cond = this.emitExpr(stmt.condition);
        this.ctx.writeLine(`if ${cond} {`);
        this.ctx.indent();
        const canImplicitReturn = isImplicitReturn && Boolean(stmt.elseBranch);
        this.emitBlock(stmt.thenBranch, canImplicitReturn);
        this.ctx.dedent();

        for (const elif of stmt.elifBranches) {
          this.ctx.writeLine(`} else if ${this.emitExpr(elif.condition)} {`);
          this.ctx.indent();
          this.emitBlock(elif.body, canImplicitReturn);
          this.ctx.dedent();
        }

        if (stmt.elseBranch) {
          this.ctx.writeLine("} else {");
          this.ctx.indent();
          this.emitBlock(stmt.elseBranch, canImplicitReturn);
          this.ctx.dedent();
          this.ctx.writeLine("}");
        } else {
          this.ctx.writeLine("}");
        }
        break;
      }
      case "WhileStmt": {
        const cond = this.emitExpr(stmt.condition);
        this.ctx.writeLine(`while ${cond} {`);
        this.ctx.indent();
        this.emitBlock(stmt.body, false);
        this.ctx.dedent();
        this.ctx.writeLine("}");
        break;
      }
      case "ForStmt": {
        const itVar = this.toSnakeCase(stmt.variable);
        const iter = this.emitExpr(stmt.iterable);
        this.ctx.writeLine(`for ${itVar} in ${iter} {`);
        this.ctx.indent();
        this.emitBlock(stmt.body, false);
        this.ctx.dedent();
        this.ctx.writeLine("}");
        break;
      }
      case "MatchStmt": {
        this.emitMatchStmt(stmt, isImplicitReturn);
        break;
      }
      case "BreakStmt": {
        this.ctx.writeLine("break;");
        break;
      }
      case "ContinueStmt": {
        this.ctx.writeLine("continue;");
        break;
      }
      case "ThrowStmt": {
        this.ctx.writeLine(`panic!("{:?}", ${this.emitExpr(stmt.expr)});`);
        break;
      }
      case "TryStmt": {
        this.emitBlock(stmt.tryBlock, isImplicitReturn);
        if (stmt.finallyBlock) {
          this.emitBlock(stmt.finallyBlock, false);
        }
        break;
      }
      case "ExprStmt": {
        const exprCode = this.emitExpr(stmt.expr);
        if (isImplicitReturn) {
          this.ctx.writeLine(exprCode);
        } else {
          this.ctx.writeLine(`${exprCode};`);
        }
        break;
      }
      default:
        break;
    }
  }

  private emitMatchStmt(stmt: MatchStmt, isImplicitReturn = false): void {
    const targetStr = this.emitExpr(stmt.target);
    this.ctx.writeLine(`match ${targetStr} {`);
    this.ctx.indent();

    for (const c of stmt.cases) {
      const patStr = this.emitPattern(c.pattern);
      const guardStr = c.guard ? ` if ${this.emitExpr(c.guard)}` : "";

      if (c.body.kind === "Block") {
        this.ctx.writeLine(`${patStr}${guardStr} => {`);
        this.ctx.indent();
        this.emitBlock(c.body, isImplicitReturn);
        this.ctx.dedent();
        this.ctx.writeLine("},");
      } else {
        const exprStr = this.emitExpr(c.body as Expr);
        this.ctx.writeLine(`${patStr}${guardStr} => ${exprStr},`);
      }
    }

    this.ctx.dedent();
    this.ctx.writeLine("}");
  }

  emitExpr(expr: Expr): string {
    switch (expr.kind) {
      case "LiteralExpr": {
        if (expr.literalKind === "string") {
          return `"${String(expr.value).replace(/"/g, '\\"')}".to_string()`;
        }
        if (expr.literalKind === "number") {
          return expr.rawValue;
        }
        if (expr.literalKind === "boolean") {
          return expr.value ? "true" : "false";
        }
        return "None";
      }
      case "TemplateLiteralExpr": {
        let fmt = "";
        for (let i = 0; i < expr.quasis.length; i++) {
          fmt += expr.quasis[i].replace(/"/g, '\\"').replace(/\{/g, "{{").replace(/\}/g, "}}");
          if (i < expr.expressions.length) {
            fmt += "{}";
          }
        }
        if (expr.expressions.length === 0) {
          return `"${fmt}".to_string()`;
        }
        const args = expr.expressions.map((e) => this.emitExpr(e)).join(", ");
        return `format!("${fmt}", ${args})`;
      }
      case "IdentifierExpr": {
        if (expr.name === "this" || expr.name === "self") {
          return "self";
        }
        const v = this.enumVariants.get(expr.name);
        if (v) {
          return `${v.parentEnum}::${expr.name}`;
        }
        if (this.structTypes.has(expr.name)) {
          return expr.name;
        }
        return this.toSnakeCase(expr.name);
      }
      case "AssignExpr":
        return `(${this.emitExpr(expr.target)} ${expr.op ?? "="} ${this.emitExpr(expr.value)})`;
      case "BinaryExpr": {
        const left = this.emitExpr(expr.left);
        const right = this.emitExpr(expr.right);
        let op = expr.operator as string;
        if (op === "and") op = "&&";
        if (op === "or") op = "||";
        if (op === "in") return `(${right}.contains(&${left}))`;
        if (op === "instanceof") {
          const typeName = expr.right.kind === "IdentifierExpr" ? expr.right.name : right;
          return `/* instanceof */ (${left}.is::<${typeName}>())`;
        }
        if (op === "**") return `(${left}.pow(${right}))`;
        if (op === ">>>") return `(((${left} as u64) >> ${right}) as _)`;
        return `(${left} ${op} ${right})`;
      }
      case "UnaryExpr": {
        const operand = this.emitExpr(expr.operand);
        if (expr.operator === "...") {
          return `...${operand}`;
        }
        const op = expr.operator === "not" ? "!" : expr.operator;
        return `${op}${operand}`;
      }
      case "PostfixTryExpr": {
        return `${this.emitExpr(expr.operand)}?`;
      }
      case "MemberAccessExpr": {
        const obj = this.emitExpr(expr.object);
        const lowered = lowerPropertyAccess(obj, expr.property, "rust");
        if (lowered.isLowered) return lowered.code;
        return `${obj}.${this.toSnakeCase(expr.property)}`;
      }
      case "IndexExpr": {
        const obj = this.emitExpr(expr.object);
        const idx = this.emitExpr(expr.index);
        return `${obj}[(${idx}) as usize]`;
      }
      case "CallExpr": {
        return this.emitCallExpr(expr);
      }
      case "ArrayLiteralExpr": {
        if (expr.elements.length === 0) {
          return "vec![]";
        }
        const elems = expr.elements.map((e) => this.emitExpr(e)).join(", ");
        return `vec![${elems}]`;
      }
      case "RecordLiteralExpr": {
        const fields = expr.properties
          .map((p) => {
            if (p.isSpread) {
              return `..${this.emitExpr(p.value)}`;
            }
            return `${this.toSnakeCase(p.key ?? "")}: ${this.emitExpr(p.value)}`;
          })
          .join(", ");
        return `{ ${fields} }`;
      }
      case "ClosureExpr": {
        const params = expr.params.map((p) => this.toSnakeCase(p.name)).join(", ");
        const body = expr.body.kind === "Block" ? "{ ... }" : this.emitExpr(expr.body);
        return `|${params}| ${body}`;
      }
      default:
        return "";
    }
  }

  private emitCallExpr(expr: CallExpr): string {
    const argCodes = expr.args.map((a) => this.emitExpr(a));

    if (expr.callee.kind === "IdentifierExpr") {
      const name = expr.callee.name;

      const loweredConst = lowerConstructor(name, argCodes, "rust");
      if (loweredConst.isLowered) return loweredConst.code;

      const enumVar = this.enumVariants.get(name);
      if (enumVar) {
        if (argCodes.length === 0) {
          return `${enumVar.parentEnum}::${name}`;
        }
        return `${enumVar.parentEnum}::${name}(${argCodes.join(", ")})`;
      }

      if (this.structTypes.has(name)) {
        return `${name}::new(${argCodes.join(", ")})`;
      }

      if (name === "clamp") return `(${argCodes[0]}).clamp(${argCodes[1]}, ${argCodes[2]})`;
      if (name === "min") return `std::cmp::min(${argCodes.join(", ")})`;
      if (name === "max") return `std::cmp::max(${argCodes.join(", ")})`;
      if (name === "abs") return `(${argCodes[0]}).abs()`;
      if (name === "sqrt") return `(${argCodes[0]}).sqrt()`;
      if (name === "floor") return `(${argCodes[0]}).floor()`;
      if (name === "ceil") return `(${argCodes[0]}).ceil()`;
      if (name === "round") return `(${argCodes[0]}).round()`;
      if (name === "sin") return `(${argCodes[0]}).sin()`;
      if (name === "cos") return `(${argCodes[0]}).cos()`;
      if (name === "tan") return `(${argCodes[0]}).tan()`;
      if (name === "atan2") return `(${argCodes[0]}).atan2(${argCodes[1]})`;
      if (name === "asin") return `(${argCodes[0]}).asin()`;
      if (name === "acos") return `(${argCodes[0]}).acos()`;
      if (name === "hypot") return `(${argCodes[0]}).hypot(${argCodes[1]})`;
      if (name === "sign") return `(${argCodes[0]}).signum()`;
      if (name === "pow") return `(${argCodes[0]}).powf(${argCodes[1]})`;

      return `${this.toSnakeCase(name)}(${argCodes.join(", ")})`;
    }

    if (expr.callee.kind === "MemberAccessExpr") {
      const objCode = this.emitExpr(expr.callee.object);
      const method = expr.callee.property;

      const loweredMethod = lowerMethodCall(objCode, method, argCodes, "rust");
      if (loweredMethod.isLowered) return loweredMethod.code;

      return `${objCode}.${this.toSnakeCase(method)}(${argCodes.join(", ")})`;
    }

    const calleeCode = this.emitExpr(expr.callee);
    return `${calleeCode}(${argCodes.join(", ")})`;
  }

  private emitPattern(pat: Pattern): string {
    switch (pat.kind) {
      case "WildcardPattern":
        return "_";
      case "IdentifierPattern": {
        const v = this.enumVariants.get(pat.name);
        if (v) {
          return `${v.parentEnum}::${pat.name}`;
        }
        return this.toSnakeCase(pat.name);
      }
      case "LiteralPattern": {
        if (pat.value.literalKind === "string") {
          return `"${pat.value.value}"`;
        }
        return pat.value.rawValue;
      }
      case "ConstructorPattern": {
        const parent = this.enumVariants.get(pat.name)?.parentEnum ?? "";
        const prefix = parent ? `${parent}::` : "";
        const sub = pat.subPatterns.map((p) => this.emitPattern(p)).join(", ");
        return `${prefix}${pat.name}(${sub})`;
      }
      default:
        return "_";
    }
  }

  emitTypeExpr(typeExpr: TypeExpr): string {
    switch (typeExpr.kind) {
      case "PrimitiveType":
        switch (typeExpr.primitive) {
          case "int":
            return "i64";
          case "float":
            return "f64";
          case "str":
          case "char":
            return "String";
          case "bool":
            return "bool";
          case "byte":
            return "u8";
          case "num":
            return "f64";
          case "nil":
          case "void":
            return "()";
          default:
            return "()";
        }
      case "NamedType": {
        let name = typeExpr.name;
        if (name === "Map") name = "HashMap";
        else if (name === "List") name = "Vec";
        if (typeExpr.typeArgs && typeExpr.typeArgs.length > 0) {
          const args = typeExpr.typeArgs.map((a) => this.emitTypeExpr(a)).join(", ");
          return `${name}<${args}>`;
        }
        return name;
      }
      case "ArrayType":
        return `Vec<${this.emitTypeExpr(typeExpr.elementType)}>`;
      case "TupleType": {
        const elements = typeExpr.elementTypes.map((e) => this.emitTypeExpr(e)).join(", ");
        return `(${elements})`;
      }
      case "OptionType":
        return `Option<${this.emitTypeExpr(typeExpr.innerType)}>`;
      case "ResultType": {
        const ok = this.emitTypeExpr(typeExpr.okType);
        const err = this.emitTypeExpr(typeExpr.errType);
        return `Result<${ok}, ${err}>`;
      }
      case "RecordType": {
        const fields = typeExpr.fields
          .map((f) => `${this.toSnakeCase(f.name)}: ${this.emitTypeExpr(f.type)}`)
          .join(", ");
        return `{ ${fields} }`;
      }
      case "RefinementType":
        return this.emitTypeExpr(typeExpr.baseType);
      default:
        return "()";
    }
  }

  private toSnakeCase(str: string): string {
    return str
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .replace(/[-\s]+/g, "_")
      .toLowerCase();
  }
}
