import type {
  Block,
  CallExpr,
  ClassDecl,
  ConstDecl,
  Expr,
  FunctionDecl,
  MatchStmt,
  Module,
  ModuleItem,
  Pattern,
  Statement,
  TypeDecl,
  TypeExpr,
  VarDecl,
} from "../core/ast.js";
import { EmitterContext, type EmitterOptions } from "./context.js";
import { lowerConstructor, lowerMethodCall, lowerPropertyAccess } from "./rewriter.js";

export class GoEmitter {
  private ctx: EmitterContext;
  private structTypes: Map<string, string[]> = new Map();
  private enumVariants: Map<string, { parentEnum: string; payloadTypes?: TypeExpr[] }> = new Map();
  private usedImports = new Set<string>();

  constructor(options: EmitterOptions = {}) {
    this.ctx = new EmitterContext("go", {
      ...options,
      indent: options.indent ?? "\t",
    });
  }

  emit(mod: Module): string {
    return this.emitModule(mod);
  }

  emitModule(mod: Module): string {
    this.structTypes.clear();
    this.enumVariants.clear();
    this.usedImports.clear();

    for (const item of mod.items) {
      if (item.kind === "TypeDecl") {
        if (item.fields) {
          this.structTypes.set(
            item.name,
            item.fields.map((f) => f.name),
          );
        } else if (item.isEnum && item.variants) {
          for (const v of item.variants) {
            this.enumVariants.set(v.name, {
              parentEnum: item.name,
              payloadTypes: v.payloadTypes,
            });
          }
        }
      } else if (item.kind === "ClassDecl") {
        const fieldNames: string[] = [];
        if (item.primaryConstructor) {
          for (const p of item.primaryConstructor) fieldNames.push(p.name);
        }
        if (item.properties) {
          for (const p of item.properties) fieldNames.push(p.name);
        }
        this.structTypes.set(item.name, fieldNames);
      }
    }

    const nonImports = mod.items.filter((i) => i.kind !== "ImportDecl");

    for (let i = 0; i < nonImports.length; i++) {
      this.emitModuleItem(nonImports[i]);
      if (i < nonImports.length - 1) {
        this.ctx.writeLine();
      }
    }

    const generatedBody = this.ctx.getOutput();

    const rawName = mod.path
      ? mod.path
          .split("/")
          .pop()
          ?.replace(/\.[a-zA-Z.]+$/, "")
      : "main";
    const packageName = this.toSnakeCase(rawName || "main").replace(/[^a-zA-Z0-9_]/g, "");

    const finalBuffer: string[] = [];
    finalBuffer.push("// Code generated by AICE 2.0 Go Emitter (Go 1.22+). DO NOT EDIT.\n\n");
    finalBuffer.push(`package ${packageName || "main"}\n\n`);

    if (generatedBody.includes("fmt.") || this.usedImports.has("fmt")) {
      this.usedImports.add("fmt");
    }
    if (generatedBody.includes("strings.") || this.usedImports.has("strings")) {
      this.usedImports.add("strings");
    }
    if (generatedBody.includes("strconv.") || this.usedImports.has("strconv")) {
      this.usedImports.add("strconv");
    }
    if (generatedBody.includes("math.") || this.usedImports.has("math")) {
      this.usedImports.add("math");
    }
    if (generatedBody.includes("errors.") || this.usedImports.has("errors")) {
      this.usedImports.add("errors");
    }

    const sortedImports = Array.from(this.usedImports).sort();
    if (sortedImports.length > 0) {
      finalBuffer.push("import (\n");
      for (const imp of sortedImports) {
        finalBuffer.push(`\t"${imp}"\n`);
      }
      finalBuffer.push(")\n\n");
    }

    finalBuffer.push(generatedBody);
    return finalBuffer.join("");
  }

  private emitModuleItem(item: ModuleItem): void {
    switch (item.kind) {
      case "TypeDecl":
        this.emitTypeDecl(item);
        break;
      case "ClassDecl":
        this.emitClassDecl(item);
        break;
      case "ConstDecl":
        this.emitConstDecl(item);
        break;
      case "VarDecl":
        this.emitVarDecl(item);
        break;
      case "FunctionDecl":
        this.emitFunctionDecl(item);
        break;
      default:
        break;
    }
  }

  private emitTypeDecl(t: TypeDecl): void {
    const nodeId = `type:${t.name}`;
    this.ctx.emitLeadingTrivia(nodeId);

    if (t.aliasType) {
      const typeStr = this.emitTypeExpr(t.aliasType);
      this.ctx.writeLine(`type ${t.name} = ${typeStr}`);
      this.ctx.emitTrailingTrivia(nodeId);
      return;
    }

    if (t.isEnum && t.variants) {
      const hasPayloads = t.variants.some((v) => v.payloadTypes && v.payloadTypes.length > 0);

      if (!hasPayloads) {
        this.ctx.writeLine(`type ${t.name} string`);
        this.ctx.writeLine();
        this.ctx.writeLine("const (");
        this.ctx.indent();
        for (const v of t.variants) {
          this.ctx.writeLine(`${t.name}${v.name} ${t.name} = "${v.name}"`);
        }
        this.ctx.dedent();
        this.ctx.writeLine(")");
      } else {
        this.ctx.writeLine(`type ${t.name}Kind string`);
        this.ctx.writeLine();
        this.ctx.writeLine("const (");
        this.ctx.indent();
        for (const v of t.variants) {
          this.ctx.writeLine(`${t.name}Kind${v.name} ${t.name}Kind = "${v.name}"`);
        }
        this.ctx.dedent();
        this.ctx.writeLine(")");
        this.ctx.writeLine();

        this.ctx.writeLine(`type ${t.name} struct {`);
        this.ctx.indent();
        this.ctx.writeLine(`Kind ${t.name}Kind \`json:"kind"\``);
        for (const v of t.variants) {
          if (v.payloadTypes && v.payloadTypes.length > 0) {
            const pt = this.emitTypeExpr(v.payloadTypes[0]);
            this.ctx.writeLine(
              `${v.name}Payload ${pt} \`json:"${this.toSnakeCase(v.name)}_payload,omitempty"\``,
            );
          }
        }
        this.ctx.dedent();
        this.ctx.writeLine("}");
      }
      this.ctx.emitTrailingTrivia(nodeId);
      return;
    }

    if (t.fields) {
      this.ctx.writeLine(`type ${t.name} struct {`);
      this.ctx.indent();
      for (const f of t.fields) {
        const fieldNodeId = `field:${t.name}.${f.name}`;
        this.ctx.emitLeadingTrivia(fieldNodeId);
        const goFieldName = this.toPascalCase(f.name);
        const typeStr = this.emitTypeExpr(f.typeAnnotation);
        this.ctx.writeLine(`${goFieldName} ${typeStr} \`json:"${this.toSnakeCase(f.name)}"\``);
        this.ctx.emitTrailingTrivia(fieldNodeId);
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");

      this.ctx.writeLine();
      const params = t.fields
        .map((f) => `${this.toCamelCase(f.name)} ${this.emitTypeExpr(f.typeAnnotation)}`)
        .join(", ");
      this.ctx.writeLine(`func New${t.name}(${params}) ${t.name} {`);
      this.ctx.indent();
      this.ctx.writeLine(`return ${t.name}{`);
      this.ctx.indent();
      for (const f of t.fields) {
        this.ctx.writeLine(`${this.toPascalCase(f.name)}: ${this.toCamelCase(f.name)},`);
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.emitTrailingTrivia(nodeId);
    }
  }

  private emitConstDecl(c: ConstDecl): void {
    const nodeId = `const:${c.name}`;
    this.ctx.emitLeadingTrivia(nodeId);
    const name = c.isExported ? c.name.charAt(0).toUpperCase() + c.name.slice(1) : c.name;
    const typeStr = c.typeAnnotation ? ` ${this.emitTypeExpr(c.typeAnnotation)}` : "";
    const val = this.emitExpr(c.value);
    this.ctx.writeLine(`const ${name}${typeStr} = ${val}`);
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitVarDecl(v: VarDecl): void {
    const nodeId = `var:${v.name}`;
    this.ctx.emitLeadingTrivia(nodeId);
    const name = v.isExported ? v.name.charAt(0).toUpperCase() + v.name.slice(1) : v.name;
    const typeStr = v.typeAnnotation ? ` ${this.emitTypeExpr(v.typeAnnotation)}` : "";
    const val = this.emitExpr(v.value);
    this.ctx.writeLine(`var ${name}${typeStr} = ${val}`);
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitClassDecl(cls: ClassDecl): void {
    const nodeId = `class:${cls.name}`;
    this.ctx.emitLeadingTrivia(nodeId);

    // Collect all fields from primaryConstructor and properties
    const fields: { name: string; typeAnnotation?: TypeExpr }[] = [];
    const seen = new Set<string>();
    if (cls.primaryConstructor) {
      for (const p of cls.primaryConstructor) {
        if (!seen.has(p.name)) {
          seen.add(p.name);
          fields.push({ name: p.name, typeAnnotation: p.typeAnnotation ?? undefined });
        }
      }
    }
    if (cls.properties) {
      for (const p of cls.properties) {
        if (!seen.has(p.name)) {
          seen.add(p.name);
          fields.push({ name: p.name, typeAnnotation: p.typeAnnotation ?? undefined });
        }
      }
    }

    this.ctx.writeLine(`type ${cls.name} struct {`);
    this.ctx.indent();
    for (const f of fields) {
      const fieldNodeId = `field:${cls.name}.${f.name}`;
      this.ctx.emitLeadingTrivia(fieldNodeId);
      const goFieldName = this.toPascalCase(f.name);
      const typeStr = f.typeAnnotation ? this.emitTypeExpr(f.typeAnnotation) : "any";
      this.ctx.writeLine(`${goFieldName} ${typeStr} \`json:"${this.toSnakeCase(f.name)}"\``);
      this.ctx.emitTrailingTrivia(fieldNodeId);
    }
    this.ctx.dedent();
    this.ctx.writeLine("}");

    // Constructor helper
    const ctorMethod = cls.methods.find(
      (m) =>
        m.name === "constructor" ||
        m.name === "new" ||
        m.name === `New${cls.name}` ||
        m.name === cls.name,
    );

    if (cls.primaryConstructor || ctorMethod || fields.length > 0) {
      this.ctx.writeLine();
      const params = (ctorMethod ? ctorMethod.params : (cls.primaryConstructor ?? fields))
        .map(
          (f) =>
            `${this.toCamelCase(f.name)} ${f.typeAnnotation ? this.emitTypeExpr(f.typeAnnotation) : "any"}`,
        )
        .join(", ");

      this.ctx.writeLine(`func New${cls.name}(${params}) *${cls.name} {`);
      this.ctx.indent();
      if (ctorMethod && ctorMethod.body.kind === "Block" && ctorMethod.body.statements.length > 0) {
        const stmts = ctorMethod.body.statements;
        const lastStmt = stmts[stmts.length - 1];
        const endsInReturn = lastStmt && lastStmt.kind === "ReturnStmt";
        const refsSelf = stmts.some((s) => this.referencesIdentifier(s, "self"));

        if (!refsSelf && endsInReturn) {
          this.emitBlock(ctorMethod.body, false);
        } else {
          this.ctx.writeLine(`self := &${cls.name}{}`);
          this.emitBlock(ctorMethod.body, false);
          if (!endsInReturn) {
            this.ctx.writeLine("return self");
          }
        }
      } else {
        this.ctx.writeLine(`return &${cls.name}{`);
        this.ctx.indent();
        for (const f of fields) {
          this.ctx.writeLine(`${this.toPascalCase(f.name)}: ${this.toCamelCase(f.name)},`);
        }
        this.ctx.dedent();
        this.ctx.writeLine("}");
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");
    }

    // Methods
    const nonCtorMethods = cls.methods.filter((m) => m !== ctorMethod);
    for (const m of nonCtorMethods) {
      this.ctx.writeLine();
      const methodNodeId = `method:${cls.name}.${m.name}`;
      this.ctx.emitLeadingTrivia(methodNodeId);
      const mName = this.toPascalCase(m.name);
      const paramsStr = m.params
        .map(
          (p) =>
            `${this.toCamelCase(p.name)} ${p.typeAnnotation ? this.emitTypeExpr(p.typeAnnotation) : "any"}`,
        )
        .join(", ");

      let isResult = false;
      let okType = "";
      let retStr = "";
      if (m.returnType) {
        if (m.returnType.kind === "ResultType") {
          isResult = true;
          okType = this.emitTypeExpr(m.returnType.okType);
          retStr = ` (${okType}, error)`;
        } else {
          const tStr = this.emitTypeExpr(m.returnType);
          if (tStr && tStr !== "void") {
            retStr = ` ${tStr}`;
          }
        }
      }

      this.ctx.writeLine(`func (self *${cls.name}) ${mName}(${paramsStr})${retStr} {`);
      this.ctx.indent();
      if (m.isExpressionBodied) {
        const exprCode = this.emitExpr(m.body as Expr);
        if (isResult) {
          this.ctx.writeLine(`return ${exprCode}, nil`);
        } else if (retStr) {
          this.ctx.writeLine(`return ${exprCode}`);
        } else {
          this.ctx.writeLine(exprCode);
        }
      } else if (m.body.kind === "Block") {
        this.emitBlock(m.body, isResult, okType, Boolean(retStr));
      }
      this.ctx.dedent();
      this.ctx.writeLine("}");
      this.ctx.emitTrailingTrivia(methodNodeId);
    }

    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitFunctionDecl(fn: FunctionDecl): void {
    const nodeId = `fn:${fn.name}`;
    this.ctx.emitLeadingTrivia(nodeId);

    if (fn.name === "__top_level__") {
      this.ctx.writeLine("func main() {");
      this.ctx.indent();
      this.emitBlock(fn.body as Block, false);
      this.ctx.dedent();
      this.ctx.writeLine("}");
      return;
    }

    const fnName = this.toPascalCase(fn.name);
    const paramsStr = fn.params
      .map(
        (p) =>
          `${this.toCamelCase(p.name)} ${p.typeAnnotation ? this.emitTypeExpr(p.typeAnnotation) : "any"}`,
      )
      .join(", ");

    let retStr = "";
    let isResult = false;
    let okType = "";

    if (fn.returnType) {
      if (fn.returnType.kind === "ResultType") {
        isResult = true;
        okType = this.emitTypeExpr(fn.returnType.okType);
        retStr = ` (${okType}, error)`;
      } else {
        const t = this.emitTypeExpr(fn.returnType);
        if (t.length > 0) {
          retStr = ` ${t}`;
        }
      }
    }

    this.ctx.writeLine(`func ${fnName}(${paramsStr})${retStr} {`);
    this.ctx.indent();

    const hasReturn = Boolean(retStr.length > 0);

    if (fn.isExpressionBodied) {
      const exprCode = this.emitExpr(fn.body as Expr);
      if (isResult) {
        this.ctx.writeLine(`return ${exprCode}, nil`);
      } else if (hasReturn) {
        this.ctx.writeLine(`return ${exprCode}`);
      } else {
        this.ctx.writeLine(exprCode);
      }
    } else {
      this.emitBlock(fn.body as Block, isResult, okType, hasReturn);
    }

    this.ctx.dedent();
    this.ctx.writeLine("}");
    this.ctx.emitTrailingTrivia(nodeId);
  }

  private emitBlock(block: Block, isResult = false, okType = "", hasReturn = false): void {
    const stmts = block.statements;
    for (let i = 0; i < stmts.length; i++) {
      const stmt = stmts[i];
      const isLast = i === stmts.length - 1;
      this.emitStatement(stmt, isResult, okType, hasReturn, isLast);
    }
  }

  private emitStatement(
    stmt: Statement,
    isResult = false,
    okType = "",
    hasReturn = false,
    isLast = false,
  ): void {
    switch (stmt.kind) {
      case "LetBinding": {
        const varName = this.toCamelCase(stmt.name);
        if (stmt.init.kind === "PostfixTryExpr") {
          const baseExpr = this.emitExpr(stmt.init.operand);
          this.ctx.writeLine(`${varName}, err := ${baseExpr}`);
          this.ctx.writeLine("if err != nil {");
          this.ctx.indent();
          const zeroVal = this.getZeroValue(okType);
          this.ctx.writeLine(`return ${zeroVal}, err`);
          this.ctx.dedent();
          this.ctx.writeLine("}");
          return;
        }
        const initStr = this.emitExpr(stmt.init);
        this.ctx.writeLine(`${varName} := ${initStr}`);
        break;
      }
      case "DestructureBinding": {
        const names = stmt.names.map((n) => this.toCamelCase(n)).join(", ");
        this.ctx.writeLine(`${names} := ${this.emitExpr(stmt.init)}`);
        break;
      }
      case "AssignStmt": {
        if (
          stmt.target.kind === "ArrayLiteralExpr" &&
          stmt.value.kind === "ArrayLiteralExpr" &&
          stmt.value.elements.length === stmt.target.elements.length
        ) {
          for (let i = 0; i < stmt.target.elements.length; i++) {
            const target = this.emitExpr(stmt.target.elements[i]);
            const value = this.emitExpr(stmt.value.elements[i]);
            if (stmt.op === "**=") {
              this.ctx.writeLine(`${target} = math.Pow(${target}, ${value})`);
            } else if (stmt.op === ">>>=") {
              this.ctx.writeLine(`${target} = ${target} >> ${value}`);
            } else {
              this.ctx.writeLine(`${target} ${stmt.op ?? "="} ${value}`);
            }
          }
        } else {
          const target = this.emitExpr(stmt.target);
          const value = this.emitExpr(stmt.value);
          if (stmt.op === "**=") {
            this.ctx.writeLine(`${target} = math.Pow(${target}, ${value})`);
          } else if (stmt.op === ">>>=") {
            this.ctx.writeLine(`${target} = ${target} >> ${value}`);
          } else {
            this.ctx.writeLine(`${target} ${stmt.op ?? "="} ${value}`);
          }
        }
        break;
      }
      case "ReturnStmt": {
        if (!stmt.value) {
          this.ctx.writeLine("return");
        } else {
          const valExpr = stmt.value;
          if (isResult) {
            if (valExpr.kind === "CallExpr" && valExpr.callee.kind === "IdentifierExpr") {
              if (valExpr.callee.name === "Ok") {
                const arg = valExpr.args[0]
                  ? this.emitExpr(valExpr.args[0])
                  : this.getZeroValue(okType);
                this.ctx.writeLine(`return ${arg}, nil`);
                return;
              }
              if (valExpr.callee.name === "Err") {
                this.usedImports.add("fmt");
                const errArg = valExpr.args[0] ? this.emitExpr(valExpr.args[0]) : '""';
                const zeroVal = this.getZeroValue(okType);
                this.ctx.writeLine(`return ${zeroVal}, fmt.Errorf("%v", ${errArg})`);
                return;
              }
            }
            this.ctx.writeLine(`return ${this.emitExpr(valExpr)}, nil`);
          } else {
            this.ctx.writeLine(`return ${this.emitExpr(valExpr)}`);
          }
        }
        break;
      }
      case "IfStmt": {
        const cond = this.emitExpr(stmt.condition);
        this.ctx.writeLine(`if ${cond} {`);
        this.ctx.indent();
        const canImplicitReturn = isLast && hasReturn && Boolean(stmt.elseBranch);
        this.emitBlock(stmt.thenBranch, isResult, okType, canImplicitReturn);
        this.ctx.dedent();

        for (const elif of stmt.elifBranches) {
          this.ctx.writeLine(`} else if ${this.emitExpr(elif.condition)} {`);
          this.ctx.indent();
          this.emitBlock(elif.body, isResult, okType, canImplicitReturn);
          this.ctx.dedent();
        }

        if (stmt.elseBranch) {
          this.ctx.writeLine("} else {");
          this.ctx.indent();
          this.emitBlock(stmt.elseBranch, isResult, okType, canImplicitReturn);
          this.ctx.dedent();
          this.ctx.writeLine("}");
        } else {
          this.ctx.writeLine("}");
        }
        break;
      }
      case "WhileStmt": {
        const cond = this.emitExpr(stmt.condition);
        this.ctx.writeLine(`for ${cond} {`);
        this.ctx.indent();
        this.emitBlock(stmt.body, isResult, okType);
        this.ctx.dedent();
        this.ctx.writeLine("}");
        break;
      }
      case "ForStmt": {
        const itVar = this.toCamelCase(stmt.variable);
        const iter = this.emitExpr(stmt.iterable);
        this.ctx.writeLine(`for _, ${itVar} := range ${iter} {`);
        this.ctx.indent();
        this.emitBlock(stmt.body, isResult, okType);
        this.ctx.dedent();
        this.ctx.writeLine("}");
        break;
      }
      case "MatchStmt": {
        this.emitMatchStmt(stmt, isResult, okType);
        break;
      }
      case "BreakStmt": {
        this.ctx.writeLine("break");
        break;
      }
      case "ContinueStmt": {
        this.ctx.writeLine("continue");
        break;
      }
      case "ThrowStmt": {
        this.ctx.writeLine(`panic(${this.emitExpr(stmt.expr)})`);
        break;
      }
      case "TryStmt": {
        if (stmt.finallyBlock) {
          this.ctx.writeLine("defer func() {");
          this.ctx.indent();
          this.emitBlock(stmt.finallyBlock, false, okType, false);
          this.ctx.dedent();
          this.ctx.writeLine("}()");
        }
        this.emitBlock(stmt.tryBlock, isResult, okType, hasReturn && isLast);
        break;
      }
      case "ExprStmt": {
        const exprCode = this.emitExpr(stmt.expr);
        if (isLast && isResult) {
          this.ctx.writeLine(`return ${exprCode}, nil`);
        } else if (isLast && hasReturn) {
          this.ctx.writeLine(`return ${exprCode}`);
        } else {
          this.ctx.writeLine(exprCode);
        }
        break;
      }
      default:
        break;
    }
  }

  private emitMatchStmt(stmt: MatchStmt, isResult = false, okType = ""): void {
    const targetStr = this.emitExpr(stmt.target);
    this.ctx.writeLine(`switch ${targetStr} {`);

    for (const c of stmt.cases) {
      const patStr = this.emitPattern(c.pattern);
      if (patStr === "default") {
        this.ctx.writeLine("default:");
      } else {
        this.ctx.writeLine(`case ${patStr}:`);
      }

      this.ctx.indent();
      if (c.body.kind === "Block") {
        this.emitBlock(c.body, isResult, okType, false);
      } else {
        this.ctx.writeLine(`return ${this.emitExpr(c.body)}`);
      }
      this.ctx.dedent();
    }

    this.ctx.writeLine("}");
  }

  emitExpr(expr: Expr): string {
    switch (expr.kind) {
      case "LiteralExpr": {
        if (expr.literalKind === "string") {
          return `"${String(expr.value).replace(/"/g, '\\"')}"`;
        }
        if (expr.literalKind === "number") {
          return expr.rawValue;
        }
        if (expr.literalKind === "boolean") {
          return expr.value ? "true" : "false";
        }
        return "nil";
      }
      case "TemplateLiteralExpr": {
        let fmt = "";
        for (let i = 0; i < expr.quasis.length; i++) {
          fmt += expr.quasis[i].replace(/"/g, '\\"').replace(/%/g, "%%");
          if (i < expr.expressions.length) {
            fmt += "%v";
          }
        }
        if (expr.expressions.length === 0) {
          return `"${fmt}"`;
        }
        const args = expr.expressions.map((e) => this.emitExpr(e)).join(", ");
        return `fmt.Sprintf("${fmt}", ${args})`;
      }
      case "IdentifierExpr": {
        const v = this.enumVariants.get(expr.name);
        if (v) {
          if (!v.payloadTypes || v.payloadTypes.length === 0) {
            return `${v.parentEnum}${expr.name}`;
          }
          return `${v.parentEnum}Kind${expr.name}`;
        }
        if (this.structTypes.has(expr.name)) {
          return expr.name;
        }
        if (expr.name === "this" || expr.name === "self") {
          return "self";
        }
        return this.toCamelCase(expr.name);
      }
      case "AssignExpr":
        return `(${this.emitExpr(expr.target)} ${expr.op ?? "="} ${this.emitExpr(expr.value)})`;
      case "BinaryExpr": {
        const left = this.emitExpr(expr.left);
        const right = this.emitExpr(expr.right);
        let op = expr.operator as string;
        if (op === "and") op = "&&";
        if (op === "or") op = "||";
        if (op === "in") return `contains(${right}, ${left})`;
        if (op === "instanceof") {
          const typeName = expr.right.kind === "IdentifierExpr" ? expr.right.name : right;
          return `/* instanceof */ func() bool { _, ok := any(${left}).(${typeName}); return ok }()`;
        }
        if (op === "**") return `math.Pow(${left}, ${right})`;
        if (op === ">>>") return `(uint64(${left}) >> ${right})`;
        return `(${left} ${op} ${right})`;
      }
      case "UnaryExpr": {
        const operand = this.emitExpr(expr.operand);
        if (expr.operator === "...") {
          return `${operand}...`;
        }
        const op = expr.operator === "not" ? "!" : expr.operator;
        return `${op}${operand}`;
      }
      case "PostfixTryExpr": {
        return this.emitExpr(expr.operand);
      }
      case "MemberAccessExpr": {
        const obj = this.emitExpr(expr.object);
        const lowered = lowerPropertyAccess(obj, expr.property, "go");
        if (lowered.isLowered) return lowered.code;
        return `${obj}.${this.toPascalCase(expr.property)}`;
      }
      case "IndexExpr": {
        const obj = this.emitExpr(expr.object);
        const idx = this.emitExpr(expr.index);
        return `${obj}[${idx}]`;
      }
      case "CallExpr": {
        return this.emitCallExpr(expr);
      }
      case "ArrayLiteralExpr": {
        if (expr.elements.length === 0) {
          return "nil";
        }
        const elems = expr.elements.map((e) => this.emitExpr(e)).join(", ");
        return `[]any{${elems}}`;
      }
      case "RecordLiteralExpr": {
        const fields = expr.properties
          .map((p) => {
            if (p.isSpread) {
              return `${this.emitExpr(p.value)}`;
            }
            return `${this.toPascalCase(p.key ?? "")}: ${this.emitExpr(p.value)}`;
          })
          .join(", ");
        return `{ ${fields} }`;
      }
      case "ClosureExpr": {
        const params = expr.params.map((p) => `${this.toCamelCase(p.name)} any`).join(", ");
        const body = expr.body.kind === "Block" ? "{ ... }" : this.emitExpr(expr.body);
        return `func(${params}) { return ${body} }`;
      }
      default:
        return "";
    }
  }

  private emitCallExpr(expr: CallExpr): string {
    const argCodes = expr.args.map((a) => this.emitExpr(a));

    if (expr.callee.kind === "IdentifierExpr") {
      const name = expr.callee.name;

      const loweredConst = lowerConstructor(name, argCodes, "go");
      if (loweredConst.isLowered) return loweredConst.code;

      const enumVar = this.enumVariants.get(name);
      if (enumVar) {
        if (!enumVar.payloadTypes || enumVar.payloadTypes.length === 0) {
          return `${enumVar.parentEnum}${name}`;
        }
        return `${enumVar.parentEnum}{ Kind: ${enumVar.parentEnum}Kind${name}, ${name}Payload: ${argCodes[0] ?? '""'} }`;
      }

      if (this.structTypes.has(name)) {
        return `New${name}(${argCodes.join(", ")})`;
      }

      if (name === "clamp")
        return `math.Max(${argCodes[1]}, math.Min(${argCodes[2]}, ${argCodes[0]}))`;
      if (name === "min") return `math.Min(${argCodes.join(", ")})`;
      if (name === "max") return `math.Max(${argCodes.join(", ")})`;
      if (name === "abs") return `math.Abs(${argCodes[0]})`;
      if (name === "floor") return `math.Floor(${argCodes[0]})`;
      if (name === "ceil") return `math.Ceil(${argCodes[0]})`;
      if (name === "round") return `math.Round(${argCodes[0]})`;
      if (name === "sqrt") return `math.Sqrt(${argCodes[0]})`;
      if (name === "sin") return `math.Sin(${argCodes[0]})`;
      if (name === "cos") return `math.Cos(${argCodes[0]})`;
      if (name === "tan") return `math.Tan(${argCodes[0]})`;
      if (name === "atan2") return `math.Atan2(${argCodes.join(", ")})`;
      if (name === "asin") return `math.Asin(${argCodes[0]})`;
      if (name === "acos") return `math.Acos(${argCodes[0]})`;
      if (name === "hypot") return `math.Hypot(${argCodes.join(", ")})`;
      if (name === "pow") return `math.Pow(${argCodes.join(", ")})`;

      return `${this.toPascalCase(name)}(${argCodes.join(", ")})`;
    }

    if (expr.callee.kind === "MemberAccessExpr") {
      const objCode = this.emitExpr(expr.callee.object);
      const method = expr.callee.property;

      const loweredMethod = lowerMethodCall(objCode, method, argCodes, "go");
      if (loweredMethod.isLowered) return loweredMethod.code;

      return `${objCode}.${this.toPascalCase(method)}(${argCodes.join(", ")})`;
    }

    const calleeCode = this.emitExpr(expr.callee);
    return `${calleeCode}(${argCodes.join(", ")})`;
  }

  private emitPattern(pat: Pattern): string {
    switch (pat.kind) {
      case "WildcardPattern":
        return "default";
      case "IdentifierPattern": {
        const v = this.enumVariants.get(pat.name);
        if (v) {
          return `${v.parentEnum}${pat.name}`;
        }
        return this.toCamelCase(pat.name);
      }
      case "LiteralPattern": {
        if (pat.value.literalKind === "string") {
          return `"${pat.value.value}"`;
        }
        return pat.value.rawValue;
      }
      case "ConstructorPattern": {
        const parent = this.enumVariants.get(pat.name)?.parentEnum ?? "";
        return `${parent}Kind${pat.name}`;
      }
      default:
        return "default";
    }
  }

  emitTypeExpr(typeExpr: TypeExpr): string {
    switch (typeExpr.kind) {
      case "PrimitiveType":
        switch (typeExpr.primitive) {
          case "int":
            return "int64";
          case "float":
            return "float64";
          case "str":
          case "char":
            return "string";
          case "bool":
            return "bool";
          case "byte":
            return "byte";
          case "num":
            return "float64";
          case "nil":
          case "void":
            return "";
          default:
            return "any";
        }
      case "NamedType": {
        if (typeExpr.name === "Map" && typeExpr.typeArgs && typeExpr.typeArgs.length === 2) {
          const keyType = this.emitTypeExpr(typeExpr.typeArgs[0]);
          const valType = this.emitTypeExpr(typeExpr.typeArgs[1]);
          return `map[${keyType}]${valType}`;
        }
        if (typeExpr.name === "List" && typeExpr.typeArgs && typeExpr.typeArgs.length === 1) {
          const elemType = this.emitTypeExpr(typeExpr.typeArgs[0]);
          return `[]${elemType}`;
        }
        if (typeExpr.typeArgs && typeExpr.typeArgs.length > 0) {
          const args = typeExpr.typeArgs.map((a) => this.emitTypeExpr(a)).join(", ");
          return `${typeExpr.name}[${args}]`;
        }
        return typeExpr.name;
      }
      case "ArrayType":
        return `[]${this.emitTypeExpr(typeExpr.elementType)}`;
      case "OptionType":
        return `*${this.emitTypeExpr(typeExpr.innerType)}`;
      case "ResultType": {
        const ok = this.emitTypeExpr(typeExpr.okType);
        return `(${ok}, error)`;
      }
      case "RecordType": {
        return "map[string]any";
      }
      case "RefinementType":
        return this.emitTypeExpr(typeExpr.baseType);
      default:
        return "any";
    }
  }

  private getZeroValue(typeStr: string): string {
    switch (typeStr) {
      case "int64":
      case "int":
        return "0";
      case "float64":
        return "0.0";
      case "string":
        return '""';
      case "bool":
        return "false";
      default:
        if (typeStr.startsWith("[]") || typeStr.startsWith("map[") || typeStr.startsWith("*")) {
          return "nil";
        }
        if (typeStr.length > 0) {
          return `${typeStr}{}`;
        }
        return "nil";
    }
  }

  private referencesIdentifier(node: any, name: string): boolean {
    if (!node || typeof node !== "object") return false;
    if (node.kind === "IdentifierExpr" && node.name === name) return true;
    for (const key of Object.keys(node)) {
      const val = node[key];
      if (Array.isArray(val)) {
        for (const item of val) {
          if (this.referencesIdentifier(item, name)) return true;
        }
      } else if (val && typeof val === "object") {
        if (this.referencesIdentifier(val, name)) return true;
      }
    }
    return false;
  }

  private toPascalCase(str: string): string {
    return str.replace(/(?:^|[-_])(\w)/g, (_, c) => c.toUpperCase());
  }

  private toCamelCase(str: string): string {
    const pascal = this.toPascalCase(str);
    return pascal.charAt(0).toLowerCase() + pascal.slice(1);
  }

  private toSnakeCase(str: string): string {
    return str
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .replace(/[-\s]+/g, "_")
      .toLowerCase();
  }
}
