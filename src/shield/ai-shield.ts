/**
 * Apply AI Exclusion & Cognitive Shield to the given project directory.
 */
export async function applyAiShield(
  dirOrOptions: string | Partial<ShieldOptions>,
  maybeOptions?: Partial<ShieldOptions>,
): Promise<ShieldApplyResult> {
  const options = typeof dirOrOptions === "string" ? maybeOptions : dirOrOptions;
  const dir = typeof dirOrOptions === "string" ? dirOrOptions : (dirOrOptions.dir ?? ".");
  const targetDir = path.resolve(options?.dir ?? dir);
  let projectCfgMode: string | undefined;
  try {
    projectCfgMode = loadProjectConfig(targetDir).mode;
  } catch {
    // ignore
  }
  const isTwinless = options?.twinless ?? projectCfgMode === "twinless";

  if (options?.twinless === true) {
    try {
      saveProjectConfig(targetDir, { mode: "twinless" });
    } catch {
      // ignore
    }
  }

  const ideSettingsEnabled = options?.ideSettings ?? !isTwinless;
  const agentIgnoresEnabled = options?.agentIgnores ?? !isTwinless;
  const cognitiveRulesEnabled = options?.cognitiveRules ?? true;
  const extensions = (options?.extensions ?? DEFAULT_EXTENSIONS).map(normalizeExtension);

  const createdFiles: string[] = [];
  const modifiedFiles: string[] = [];
  const activeShields: string[] = [];

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  // If switching to twinless mode and ignore files exist with old shield markers, strip them so native files are never hidden
  if (isTwinless && !options?.agentIgnores) {
    for (const ignoreName of AGENT_IGNORE_FILES) {
      const ignorePath = path.join(targetDir, ignoreName);
      if (fs.existsSync(ignorePath)) {
        const existingContent = fs.readFileSync(ignorePath, "utf-8");
        const { remaining, removed } = removeMarkerBlock(
          existingContent,
          SHIELD_START_MARKER,
          SHIELD_END_MARKER,
        );
        if (removed) {
          fs.writeFileSync(ignorePath, remaining, "utf-8");
          modifiedFiles.push(ignorePath);
        }
      }
    }
  }

  // 1. IDE Settings (.vscode/settings.json)
  if (ideSettingsEnabled) {
    const vscodeDir = path.join(targetDir, ".vscode");
    const settingsPath = path.join(vscodeDir, "settings.json");

    if (!fs.existsSync(vscodeDir)) {
      fs.mkdirSync(vscodeDir, { recursive: true });
    }

    const fileExisted = fs.existsSync(settingsPath);
    let originalRaw = "";
    let settings: Record<string, unknown> = {};

    if (fileExisted) {
      try {
        originalRaw = fs.readFileSync(settingsPath, "utf-8");
        settings = parseJsonSafe(originalRaw);
      } catch {
        settings = {};
      }
    }

    const filesExclude =
      typeof settings["files.exclude"] === "object" && settings["files.exclude"] !== null
        ? { ...(settings["files.exclude"] as Record<string, unknown>) }
        : {};

    const searchExclude =
      typeof settings["search.exclude"] === "object" && settings["search.exclude"] !== null
        ? { ...(settings["search.exclude"] as Record<string, unknown>) }
        : {};

    for (const ext of extensions) {
      const globKey = `**/*${ext}`;
      const whenValue = { when: `$(basename)${ext}.ail` };
      filesExclude[globKey] = whenValue;
      searchExclude[globKey] = whenValue;
    }

    settings["files.exclude"] = filesExclude;
    settings["search.exclude"] = searchExclude;

    const formattedJson = `${JSON.stringify(settings, null, 2)}\n`;

    if (!fileExisted) {
      fs.writeFileSync(settingsPath, formattedJson, "utf-8");
      createdFiles.push(settingsPath);
    } else if (formattedJson !== originalRaw) {
      fs.writeFileSync(settingsPath, formattedJson, "utf-8");
      modifiedFiles.push(settingsPath);
    }

    activeShields.push("ideSettings");
  }

  // 2. Agent Ignore Files (.cursorignore, .geminiignore, .aiderignore, .agentignore)
  if (agentIgnoresEnabled) {
    const ignoreBlock = generateShieldIgnoreBlock(extensions);

    for (const ignoreName of AGENT_IGNORE_FILES) {
      const ignorePath = path.join(targetDir, ignoreName);
      const fileExisted = fs.existsSync(ignorePath);

      if (!fileExisted) {
        fs.writeFileSync(ignorePath, `${ignoreBlock}\n`, "utf-8");
        createdFiles.push(ignorePath);
      } else {
        const existingContent = fs.readFileSync(ignorePath, "utf-8");
        const { newContent, changed } = updateMarkerBlock(
          existingContent,
          SHIELD_START_MARKER,
          SHIELD_END_MARKER,
          ignoreBlock,
        );

        if (changed) {
          fs.writeFileSync(ignorePath, newContent, "utf-8");
          modifiedFiles.push(ignorePath);
        }
      }
    }

    activeShields.push("agentIgnores");
  }

  // 3. Cognitive Rule Files (AGENTS.md, GEMINI.md, .cursorrules)
  if (cognitiveRulesEnabled) {
    let idioms = options?.idioms;
    if (!idioms) {
      try {
        idioms = loadProjectConfig(targetDir).idioms;
      } catch {
        // ignore
      }
    }

    // AGENTS.md
    const agentsMdPath = path.join(targetDir, "AGENTS.md");
    const agentsMdExisted = fs.existsSync(agentsMdPath);
    const agentsBlock = isTwinless
      ? generateTwinlessAgentsMdContent({ idioms })
      : generateCognitiveAgentsMdContent({ idioms });

    if (!agentsMdExisted) {
      fs.writeFileSync(agentsMdPath, `${agentsBlock}\n`, "utf-8");
      createdFiles.push(agentsMdPath);
    } else {
      const existing = fs.readFileSync(agentsMdPath, "utf-8");
      const { newContent, changed } = updateMarkerBlock(
        existing,
        COGNITIVE_RULES_MD_START,
        COGNITIVE_RULES_MD_END,
        agentsBlock,
      );
      if (changed) {
        fs.writeFileSync(agentsMdPath, newContent, "utf-8");
        modifiedFiles.push(agentsMdPath);
      }
    }

    // GEMINI.md: Always synchronized whenever cognitive rules are enabled
    const geminiMdPath = path.join(targetDir, "GEMINI.md");
    const geminiMdExisted = fs.existsSync(geminiMdPath);
    if (!geminiMdExisted) {
      fs.writeFileSync(geminiMdPath, `${agentsBlock}\n`, "utf-8");
      createdFiles.push(geminiMdPath);
    } else {
      const existing = fs.readFileSync(geminiMdPath, "utf-8");
      const { newContent, changed } = updateMarkerBlock(
        existing,
        COGNITIVE_RULES_MD_START,
        COGNITIVE_RULES_MD_END,
        agentsBlock,
      );
      if (changed) {
        fs.writeFileSync(geminiMdPath, newContent, "utf-8");
        modifiedFiles.push(geminiMdPath);
      }
    }

    // .cursorrules
    const cursorRulesPath = path.join(targetDir, ".cursorrules");
    const cursorRulesExisted = fs.existsSync(cursorRulesPath);
    const cursorRulesBlock = isTwinless
      ? generateTwinlessCursorRulesContent({ idioms })
      : generateCognitiveCursorRulesContent({ idioms });

    if (!cursorRulesExisted) {
      fs.writeFileSync(cursorRulesPath, `${cursorRulesBlock}\n`, "utf-8");
      createdFiles.push(cursorRulesPath);
    } else {
      const existing = fs.readFileSync(cursorRulesPath, "utf-8");
      const { newContent, changed } = updateMarkerBlock(
        existing,
        COGNITIVE_RULES_TEXT_START,
        COGNITIVE_RULES_TEXT_END,
        cursorRulesBlock,
      );
      if (changed) {
        fs.writeFileSync(cursorRulesPath, newContent, "utf-8");
        modifiedFiles.push(cursorRulesPath);
      }
    }

    activeShields.push("cognitiveRules");
  }

  // 4. Lifecycle Hooks (.agents/hooks.json and .agents/ail-shield-hook.mjs)
  const lifecycleHooksEnabled = options?.lifecycleHooks ?? false;
  if (lifecycleHooksEnabled) {
    const agentsDir = path.join(targetDir, ".agents");
    if (!fs.existsSync(agentsDir)) {
      fs.mkdirSync(agentsDir, { recursive: true });
    }

    const hookScriptPath = path.join(agentsDir, "ail-shield-hook.mjs");
    const hookScriptExisted = fs.existsSync(hookScriptPath);
    const hookScriptContent = generateAilShieldHookScript();
    fs.writeFileSync(hookScriptPath, hookScriptContent, { mode: 0o755 });
    if (!hookScriptExisted) {
      createdFiles.push(hookScriptPath);
    } else {
      modifiedFiles.push(hookScriptPath);
    }

    // Also write .agents/rules/ail-shield.md for Antigravity directory-based rule discovery
    const rulesDir = path.join(agentsDir, "rules");
    if (!fs.existsSync(rulesDir)) {
      fs.mkdirSync(rulesDir, { recursive: true });
    }
    const ruleMdPath = path.join(rulesDir, "ail-shield.md");
    const ruleMdExisted = fs.existsSync(ruleMdPath);
    fs.writeFileSync(ruleMdPath, `${generateCognitiveAgentsMdContent()}\n`, "utf-8");
    if (!ruleMdExisted) {
      createdFiles.push(ruleMdPath);
    } else {
      modifiedFiles.push(ruleMdPath);
    }

    const hooksJsonPath = path.join(agentsDir, "hooks.json");
    const hooksJsonExisted = fs.existsSync(hooksJsonPath);
    let hooksData: Record<string, unknown> = {};
    if (hooksJsonExisted) {
      try {
        hooksData = parseJsonSafe(fs.readFileSync(hooksJsonPath, "utf-8"));
      } catch {
        hooksData = {};
      }
    }

    const fallbackNodeScript =
      'node -e \'const fs=require("fs"),p=fs.existsSync("./ail-shield-hook.mjs")?"./ail-shield-hook.mjs":".agents/ail-shield-hook.mjs";import(require("path").resolve(p))\'';

    hooksData["ail-shield-interceptor"] = {
      PreToolUse: [
        {
          matcher: "view_file|replace_file_content|write_to_file",
          hooks: [
            {
              type: "command",
              command: `command -v ail >/dev/null 2>&1 && ail shield intercept || ${fallbackNodeScript}`,
            },
          ],
        },
      ],
    };

    // Clean up any legacy recursive symlink (.agents/.agents)
    const nestedAgentsLink = path.join(agentsDir, ".agents");
    try {
      if (fs.lstatSync(nestedAgentsLink)) {
        fs.unlinkSync(nestedAgentsLink);
      }
    } catch {
      // ignore if does not exist
    }

    const formattedHooksJson = `${JSON.stringify(hooksData, null, 2)}\n`;
    fs.writeFileSync(hooksJsonPath, formattedHooksJson, "utf-8");
    if (!hooksJsonExisted) {
      createdFiles.push(hooksJsonPath);
    } else {
      modifiedFiles.push(hooksJsonPath);
    }

    activeShields.push("lifecycleHooks");
  }

  return {
    createdFiles,
    modifiedFiles,
    activeShields,
  };
}

