import * as fs from "node:fs";
import * as path from "node:path";

export interface ShieldOptions {
  dir: string;
  ideSettings?: boolean; // default true (.vscode/settings.json)
  agentIgnores?: boolean; // default true (.cursorignore, .geminiignore, .aiderignore, .agentignore)
  cognitiveRules?: boolean; // default true (AGENTS.md, .cursorrules)
  extensions?: string[]; // default [".ts", ".tsx", ".css", ".html", ".py", ".cpp", ".hpp", ".h"]
}

export interface ShieldApplyResult {
  createdFiles: string[];
  modifiedFiles: string[];
  activeShields: string[];
}

export interface ShieldRemoveResult {
  removedFiles: string[];
  revertedFiles: string[];
}

export interface ShieldStatus {
  isActive: boolean;
  ideSettingsConfigured: boolean;
  agentIgnoresConfigured: boolean;
  cognitiveRulesConfigured: boolean;
  details: Record<string, boolean>;
}

export const DEFAULT_EXTENSIONS: string[] = [
  ".ts",
  ".tsx",
  ".css",
  ".html",
  ".py",
  ".cpp",
  ".hpp",
  ".h",
];

export const AGENT_IGNORE_FILES = [
  ".cursorignore",
  ".geminiignore",
  ".aiderignore",
  ".agentignore",
] as const;

export const SHIELD_START_MARKER = "# >>> AIL-SHIELD-START >>>";
export const SHIELD_END_MARKER = "# <<< AIL-SHIELD-END <<<";
export const SHIELD_HEADER_COMMENT =
  "# Auto-generated by AIL. Target files hidden when .ail sibling exists.";

export const COGNITIVE_RULES_MD_START = "<!-- >>> AIL-COGNITIVE-RULE-START >>> -->";
export const COGNITIVE_RULES_MD_END = "<!-- <<< AIL-COGNITIVE-RULE-END <<< -->";

export const COGNITIVE_RULES_TEXT_START = "# >>> AIL-COGNITIVE-RULE-START >>>";
export const COGNITIVE_RULES_TEXT_END = "# <<< AIL-COGNITIVE-RULE-END <<<";

function normalizeExtension(ext: string): string {
  const trimmed = ext.trim();
  return trimmed.startsWith(".") ? trimmed : `.${trimmed}`;
}

export function generateShieldIgnoreBlock(extensions: string[] = DEFAULT_EXTENSIONS): string {
  const normalizedExts = Array.from(new Set(extensions.map(normalizeExtension)));
  const lines = [
    SHIELD_START_MARKER,
    SHIELD_HEADER_COMMENT,
    ...normalizedExts.map((ext) => `*${ext}`),
    "!*.ail",
    "!*.trivia.json",
    SHIELD_END_MARKER,
  ];
  return lines.join("\n");
}

export function generateCognitiveAgentsMdContent(): string {
  return [
    COGNITIVE_RULES_MD_START,
    "# AIL Project Directives for AI Coding Agents",
    "",
    "> **CRITICAL DIRECTIVE**: This project is authoritatively developed in AIL (*.ail).",
    "> Target files (`*.ts`, `*.tsx`, `*.css`, `*.html`, `*.py`, `*.cpp`, `*.hpp`, `*.h`, etc.) are **machine-generated, read-only build artifacts**.",
    "",
    "## Agent Instructions:",
    "1. **Source of Truth**: Always read, inspect, create, and modify `*.ail` source files.",
    "2. **Never Edit Target Files Directly**: Any changes made directly to target files will be overwritten by the AIL compiler (`ail compile` or `ail compile-all`).",
    "3. **Compilation**: When target artifacts are needed, invoke `ail compile <file.ail>` or `ail compile-all`.",
    "4. **Verification**: Run `ail verify <file.ail>` to verify syntax and type soundness.",
    COGNITIVE_RULES_MD_END,
  ].join("\n");
}

export function generateCognitiveCursorRulesContent(): string {
  return [
    COGNITIVE_RULES_TEXT_START,
    "# AIL Project Directives for AI Coding Agents",
    "# CRITICAL DIRECTIVE: This repository is authoritatively developed in AIL (*.ail).",
    "# All target files (*.ts, *.tsx, *.css, *.html, *.py, *.cpp, *.hpp, *.h, etc.) are machine-generated read-only build artifacts.",
    "# Agents must only read, create, and modify *.ail source files.",
    "# Never edit target files directly; changes will be overwritten by `ail compile`.",
    "# Run `ail compile <file.ail>` to produce target files or `ail verify <file.ail>` to check code.",
    COGNITIVE_RULES_TEXT_END,
  ].join("\n");
}

function parseJsonSafe(content: string): Record<string, unknown> {
  try {
    return JSON.parse(content);
  } catch {
    const stripped = content.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^\\:])\/\/.*$/gm, "$1");
    return JSON.parse(stripped);
  }
}

function updateMarkerBlock(
  content: string,
  startMarker: string,
  endMarker: string,
  newBlock: string,
): { newContent: string; changed: boolean } {
  const startIndex = content.indexOf(startMarker);
  const endIndex = content.indexOf(endMarker);

  if (startIndex !== -1 && endIndex !== -1 && endIndex >= startIndex) {
    const afterEnd = endIndex + endMarker.length;
    const before = content.slice(0, startIndex);
    const after = content.slice(afterEnd).replace(/^\r?\n/, "");
    const combined =
      (before.trimEnd() ? `${before.trimEnd()}\n\n` : "") +
      newBlock +
      (after.trimStart() ? `\n\n${after.trimStart()}` : "");
    const normalized = `${combined.trim()}\n`;
    return {
      newContent: normalized,
      changed: normalized !== content,
    };
  }

  const trimmed = content.trim();
  const normalized = trimmed ? `${trimmed}\n\n${newBlock}\n` : `${newBlock}\n`;
  return {
    newContent: normalized,
    changed: normalized !== content,
  };
}

function removeMarkerBlock(
  content: string,
  startMarker: string,
  endMarker: string,
): { remaining: string; removed: boolean } {
  const startIndex = content.indexOf(startMarker);
  const endIndex = content.indexOf(endMarker);

  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    return { remaining: content, removed: false };
  }

  const afterEnd = endIndex + endMarker.length;
  const before = content.slice(0, startIndex);
  const after = content.slice(afterEnd).replace(/^\r?\n/, "");
  const remaining = `${before.trimEnd()}${after ? `\n${after.trimStart()}` : ""}`.trim();
  return {
    remaining: remaining ? `${remaining}\n` : "",
    removed: true,
  };
}

function hasCognitiveRule(content: string): boolean {
  return (
    content.includes(COGNITIVE_RULES_MD_START) ||
    content.includes(COGNITIVE_RULES_TEXT_START) ||
    (content.includes("AIL") && content.includes("*.ail"))
  );
}

function removeCognitiveRule(content: string): { remaining: string; removed: boolean } {
  if (content.includes(COGNITIVE_RULES_MD_START)) {
    return removeMarkerBlock(content, COGNITIVE_RULES_MD_START, COGNITIVE_RULES_MD_END);
  }
  if (content.includes(COGNITIVE_RULES_TEXT_START)) {
    return removeMarkerBlock(content, COGNITIVE_RULES_TEXT_START, COGNITIVE_RULES_TEXT_END);
  }
  return { remaining: content, removed: false };
}

/**
 * Apply AI Exclusion & Cognitive Shield to the given project directory.
 */
export async function applyAiShield(
  dir: string,
  options?: Partial<ShieldOptions>,
): Promise<ShieldApplyResult> {
  const targetDir = path.resolve(options?.dir ?? dir);
  const ideSettingsEnabled = options?.ideSettings ?? true;
  const agentIgnoresEnabled = options?.agentIgnores ?? true;
  const cognitiveRulesEnabled = options?.cognitiveRules ?? true;
  const extensions = (options?.extensions ?? DEFAULT_EXTENSIONS).map(normalizeExtension);

  const createdFiles: string[] = [];
  const modifiedFiles: string[] = [];
  const activeShields: string[] = [];

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  // 1. IDE Settings (.vscode/settings.json)
  if (ideSettingsEnabled) {
    const vscodeDir = path.join(targetDir, ".vscode");
    const settingsPath = path.join(vscodeDir, "settings.json");

    if (!fs.existsSync(vscodeDir)) {
      fs.mkdirSync(vscodeDir, { recursive: true });
    }

    const fileExisted = fs.existsSync(settingsPath);
    let originalRaw = "";
    let settings: Record<string, unknown> = {};

    if (fileExisted) {
      try {
        originalRaw = fs.readFileSync(settingsPath, "utf-8");
        settings = parseJsonSafe(originalRaw);
      } catch {
        settings = {};
      }
    }

    const filesExclude =
      typeof settings["files.exclude"] === "object" && settings["files.exclude"] !== null
        ? { ...(settings["files.exclude"] as Record<string, unknown>) }
        : {};

    const searchExclude =
      typeof settings["search.exclude"] === "object" && settings["search.exclude"] !== null
        ? { ...(settings["search.exclude"] as Record<string, unknown>) }
        : {};

    for (const ext of extensions) {
      const globKey = `**/*${ext}`;
      const whenValue = { when: `$(basename)${ext}.ail` };
      filesExclude[globKey] = whenValue;
      searchExclude[globKey] = whenValue;
    }

    settings["files.exclude"] = filesExclude;
    settings["search.exclude"] = searchExclude;

    const formattedJson = `${JSON.stringify(settings, null, 2)}\n`;

    if (!fileExisted) {
      fs.writeFileSync(settingsPath, formattedJson, "utf-8");
      createdFiles.push(settingsPath);
    } else if (formattedJson !== originalRaw) {
      fs.writeFileSync(settingsPath, formattedJson, "utf-8");
      modifiedFiles.push(settingsPath);
    }

    activeShields.push("ideSettings");
  }

  // 2. Agent Ignore Files (.cursorignore, .geminiignore, .aiderignore, .agentignore)
  if (agentIgnoresEnabled) {
    const ignoreBlock = generateShieldIgnoreBlock(extensions);

    for (const ignoreName of AGENT_IGNORE_FILES) {
      const ignorePath = path.join(targetDir, ignoreName);
      const fileExisted = fs.existsSync(ignorePath);

      if (!fileExisted) {
        fs.writeFileSync(ignorePath, `${ignoreBlock}\n`, "utf-8");
        createdFiles.push(ignorePath);
      } else {
        const existingContent = fs.readFileSync(ignorePath, "utf-8");
        const { newContent, changed } = updateMarkerBlock(
          existingContent,
          SHIELD_START_MARKER,
          SHIELD_END_MARKER,
          ignoreBlock,
        );

        if (changed) {
          fs.writeFileSync(ignorePath, newContent, "utf-8");
          modifiedFiles.push(ignorePath);
        }
      }
    }

    activeShields.push("agentIgnores");
  }

  // 3. Cognitive Rule Files (AGENTS.md, .cursorrules)
  if (cognitiveRulesEnabled) {
    // AGENTS.md
    const agentsMdPath = path.join(targetDir, "AGENTS.md");
    const agentsMdExisted = fs.existsSync(agentsMdPath);
    const agentsBlock = generateCognitiveAgentsMdContent();

    if (!agentsMdExisted) {
      fs.writeFileSync(agentsMdPath, `${agentsBlock}\n`, "utf-8");
      createdFiles.push(agentsMdPath);
    } else {
      const existing = fs.readFileSync(agentsMdPath, "utf-8");
      const { newContent, changed } = updateMarkerBlock(
        existing,
        COGNITIVE_RULES_MD_START,
        COGNITIVE_RULES_MD_END,
        agentsBlock,
      );
      if (changed) {
        fs.writeFileSync(agentsMdPath, newContent, "utf-8");
        modifiedFiles.push(agentsMdPath);
      }
    }

    // .cursorrules
    const cursorRulesPath = path.join(targetDir, ".cursorrules");
    const cursorRulesExisted = fs.existsSync(cursorRulesPath);
    const cursorRulesBlock = generateCognitiveCursorRulesContent();

    if (!cursorRulesExisted) {
      fs.writeFileSync(cursorRulesPath, `${cursorRulesBlock}\n`, "utf-8");
      createdFiles.push(cursorRulesPath);
    } else {
      const existing = fs.readFileSync(cursorRulesPath, "utf-8");
      const { newContent, changed } = updateMarkerBlock(
        existing,
        COGNITIVE_RULES_TEXT_START,
        COGNITIVE_RULES_TEXT_END,
        cursorRulesBlock,
      );
      if (changed) {
        fs.writeFileSync(cursorRulesPath, newContent, "utf-8");
        modifiedFiles.push(cursorRulesPath);
      }
    }

    activeShields.push("cognitiveRules");
  }

  return {
    createdFiles,
    modifiedFiles,
    activeShields,
  };
}

/**
 * Remove AI Exclusion & Cognitive Shield from the given project directory.
 */
export async function removeAiShield(
  dir: string,
  options?: Partial<ShieldOptions>,
): Promise<ShieldRemoveResult> {
  const targetDir = path.resolve(options?.dir ?? dir);
  const ideSettingsEnabled = options?.ideSettings ?? true;
  const agentIgnoresEnabled = options?.agentIgnores ?? true;
  const cognitiveRulesEnabled = options?.cognitiveRules ?? true;

  const removedFiles: string[] = [];
  const revertedFiles: string[] = [];

  if (!fs.existsSync(targetDir)) {
    return { removedFiles, revertedFiles };
  }

  // 1. Clean IDE Settings (.vscode/settings.json)
  if (ideSettingsEnabled) {
    const settingsPath = path.join(targetDir, ".vscode", "settings.json");
    if (fs.existsSync(settingsPath)) {
      try {
        const raw = fs.readFileSync(settingsPath, "utf-8");
        const json = parseJsonSafe(raw);
        let modified = false;

        const filesExclude =
          typeof json["files.exclude"] === "object" && json["files.exclude"] !== null
            ? (json["files.exclude"] as Record<string, unknown>)
            : null;

        if (filesExclude) {
          for (const [key, val] of Object.entries(filesExclude)) {
            if (
              typeof val === "object" &&
              val !== null &&
              typeof (val as Record<string, unknown>).when === "string" &&
              ((val as Record<string, unknown>).when as string).endsWith(".ail")
            ) {
              delete filesExclude[key];
              modified = true;
            }
          }
          if (Object.keys(filesExclude).length === 0) {
            delete json["files.exclude"];
            modified = true;
          }
        }

        const searchExclude =
          typeof json["search.exclude"] === "object" && json["search.exclude"] !== null
            ? (json["search.exclude"] as Record<string, unknown>)
            : null;

        if (searchExclude) {
          for (const [key, val] of Object.entries(searchExclude)) {
            if (
              typeof val === "object" &&
              val !== null &&
              typeof (val as Record<string, unknown>).when === "string" &&
              ((val as Record<string, unknown>).when as string).endsWith(".ail")
            ) {
              delete searchExclude[key];
              modified = true;
            }
          }
          if (Object.keys(searchExclude).length === 0) {
            delete json["search.exclude"];
            modified = true;
          }
        }

        if (modified) {
          if (Object.keys(json).length === 0) {
            fs.unlinkSync(settingsPath);
            removedFiles.push(settingsPath);
            const vscodeDir = path.dirname(settingsPath);
            try {
              if (fs.readdirSync(vscodeDir).length === 0) {
                fs.rmdirSync(vscodeDir);
              }
            } catch {
              // ignore error
            }
          } else {
            fs.writeFileSync(settingsPath, `${JSON.stringify(json, null, 2)}\n`, "utf-8");
            revertedFiles.push(settingsPath);
          }
        }
      } catch {
        // ignore parse error
      }
    }
  }

  // 2. Clean Agent Ignore Files
  if (agentIgnoresEnabled) {
    for (const ignoreName of AGENT_IGNORE_FILES) {
      const ignorePath = path.join(targetDir, ignoreName);
      if (fs.existsSync(ignorePath)) {
        const content = fs.readFileSync(ignorePath, "utf-8");
        const { remaining, removed } = removeMarkerBlock(
          content,
          SHIELD_START_MARKER,
          SHIELD_END_MARKER,
        );

        if (removed) {
          if (!remaining.trim()) {
            fs.unlinkSync(ignorePath);
            removedFiles.push(ignorePath);
          } else {
            fs.writeFileSync(ignorePath, remaining, "utf-8");
            revertedFiles.push(ignorePath);
          }
        }
      }
    }
  }

  // 3. Clean Cognitive Rule Files
  if (cognitiveRulesEnabled) {
    const agentsMdPath = path.join(targetDir, "AGENTS.md");
    if (fs.existsSync(agentsMdPath)) {
      const content = fs.readFileSync(agentsMdPath, "utf-8");
      const { remaining, removed } = removeCognitiveRule(content);
      if (removed) {
        if (!remaining.trim()) {
          fs.unlinkSync(agentsMdPath);
          removedFiles.push(agentsMdPath);
        } else {
          fs.writeFileSync(agentsMdPath, remaining, "utf-8");
          revertedFiles.push(agentsMdPath);
        }
      }
    }

    const cursorRulesPath = path.join(targetDir, ".cursorrules");
    if (fs.existsSync(cursorRulesPath)) {
      const content = fs.readFileSync(cursorRulesPath, "utf-8");
      const { remaining, removed } = removeCognitiveRule(content);
      if (removed) {
        if (!remaining.trim()) {
          fs.unlinkSync(cursorRulesPath);
          removedFiles.push(cursorRulesPath);
        } else {
          fs.writeFileSync(cursorRulesPath, remaining, "utf-8");
          revertedFiles.push(cursorRulesPath);
        }
      }
    }
  }

  return {
    removedFiles,
    revertedFiles,
  };
}

/**
 * Check whether AI Exclusion & Cognitive Shield is active and configured in the directory.
 */
export async function checkAiShieldStatus(
  dir: string,
  options?: Partial<ShieldOptions>,
): Promise<ShieldStatus> {
  const targetDir = path.resolve(options?.dir ?? dir);
  const extensions = (options?.extensions ?? DEFAULT_EXTENSIONS).map(normalizeExtension);

  const details: Record<string, boolean> = {
    ".vscode/settings.json": false,
    ".cursorignore": false,
    ".geminiignore": false,
    ".aiderignore": false,
    ".agentignore": false,
    "AGENTS.md": false,
    ".cursorrules": false,
  };

  if (!fs.existsSync(targetDir)) {
    return {
      isActive: false,
      ideSettingsConfigured: false,
      agentIgnoresConfigured: false,
      cognitiveRulesConfigured: false,
      details,
    };
  }

  // 1. Check .vscode/settings.json
  const settingsPath = path.join(targetDir, ".vscode", "settings.json");
  if (fs.existsSync(settingsPath)) {
    try {
      const content = fs.readFileSync(settingsPath, "utf-8");
      const json = parseJsonSafe(content);
      const filesExclude =
        typeof json["files.exclude"] === "object" && json["files.exclude"] !== null
          ? (json["files.exclude"] as Record<string, unknown>)
          : {};
      const searchExclude =
        typeof json["search.exclude"] === "object" && json["search.exclude"] !== null
          ? (json["search.exclude"] as Record<string, unknown>)
          : {};

      const hasFilesExclude = extensions.some((ext) => {
        const val = filesExclude[`**/*${ext}`] as Record<string, unknown> | undefined;
        return val?.when === `$(basename)${ext}.ail`;
      });

      const hasSearchExclude = extensions.some((ext) => {
        const val = searchExclude[`**/*${ext}`] as Record<string, unknown> | undefined;
        return val?.when === `$(basename)${ext}.ail`;
      });

      details[".vscode/settings.json"] = hasFilesExclude && hasSearchExclude;
    } catch {
      details[".vscode/settings.json"] = false;
    }
  }

  // 2. Check Agent Ignore Files
  for (const ignoreName of AGENT_IGNORE_FILES) {
    const ignorePath = path.join(targetDir, ignoreName);
    if (fs.existsSync(ignorePath)) {
      const content = fs.readFileSync(ignorePath, "utf-8");
      details[ignoreName] =
        content.includes(SHIELD_START_MARKER) && content.includes(SHIELD_END_MARKER);
    } else {
      details[ignoreName] = false;
    }
  }

  // 3. Check Cognitive Rule Files
  const agentsMdPath = path.join(targetDir, "AGENTS.md");
  if (fs.existsSync(agentsMdPath)) {
    const content = fs.readFileSync(agentsMdPath, "utf-8");
    details["AGENTS.md"] = hasCognitiveRule(content);
  }

  const cursorRulesPath = path.join(targetDir, ".cursorrules");
  if (fs.existsSync(cursorRulesPath)) {
    const content = fs.readFileSync(cursorRulesPath, "utf-8");
    details[".cursorrules"] = hasCognitiveRule(content);
  }

  const ideSettingsConfigured = details[".vscode/settings.json"] === true;
  const agentIgnoresConfigured = AGENT_IGNORE_FILES.every((f) => details[f] === true);
  const cognitiveRulesConfigured =
    details["AGENTS.md"] === true && details[".cursorrules"] === true;

  details.ideSettings = ideSettingsConfigured;
  details.agentIgnores = agentIgnoresConfigured;
  details.cognitiveRules = cognitiveRulesConfigured;

  const isActive = ideSettingsConfigured || agentIgnoresConfigured || cognitiveRulesConfigured;

  return {
    isActive,
    ideSettingsConfigured,
    agentIgnoresConfigured,
    cognitiveRulesConfigured,
    details,
  };
}
